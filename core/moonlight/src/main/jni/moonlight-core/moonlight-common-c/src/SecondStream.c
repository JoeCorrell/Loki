/** Failure notification captured for delivery away from the receive thread. */
typedef struct _SECOND_DISPLAY_FAILURE_NOTIFICATION {
    SECOND_DISPLAY_STATUS_CALLBACK callback;  ///< Callback belonging to the failed session.
    unsigned int generation;  ///< Session generation used to reject stale reconnect callbacks.
    int errorCode;  ///< Native receive-stream failure.
} SECOND_DISPLAY_FAILURE_NOTIFICATION, *PSECOND_DISPLAY_FAILURE_NOTIFICATION;

/**
 * @brief Publish a second-display status transition exactly once.
 *
 * @param active Whether stream two is currently usable.
 * @param errorCode Failure code, or zero for an intentional transition.
 */
static void notifySecondDisplayStatus(bool active, int errorCode) {
    SECOND_DISPLAY_STATUS_CALLBACK callback = atomic_load(&secondStreamStatusCallback);
    bool previous = atomic_exchange(&secondStreamStatusActive, active);
    if (previous != active && callback != NULL) {
        callback(active, errorCode);
    }
}

/**
 * @brief Deliver an asynchronous second-stream failure notification.
 *
 * @param context Captured `SECOND_DISPLAY_FAILURE_NOTIFICATION` instance.
 */
static void secondDisplayFailureNotificationThread(void* context) {
    PSECOND_DISPLAY_FAILURE_NOTIFICATION notification = context;

    if (notification->generation == atomic_load(&secondStreamGeneration)) {
        notification->callback(false, notification->errorCode);
    }

    free(notification);
}

/**
 * @brief Publish failure without running client teardown on the receive thread.
 *
 * A client is allowed to detach the second display from this callback. Dispatch
 * on another thread prevents that detach from trying to join the receive thread
 * that is currently executing the callback.
 *
 * @param errorCode Native receive-stream failure.
 */
static void notifySecondDisplayFailure(int errorCode) {
    PSECOND_DISPLAY_FAILURE_NOTIFICATION notification;
    SECOND_DISPLAY_STATUS_CALLBACK callback;
    PLT_THREAD notificationThread;
    int err;

    callback = atomic_load(&secondStreamStatusCallback);
    if (!atomic_exchange(&secondStreamStatusActive, false) || callback == NULL) {
        return;
    }

    notification = malloc(sizeof(*notification));
    if (notification == NULL) {
        Limelog("Unable to allocate second display failure callback\n");
        return;
    }

    notification->callback = callback;
    notification->generation = atomic_load(&secondStreamGeneration);
    notification->errorCode = errorCode;

    err = PltCreateThread("SecondDispFail", secondDisplayFailureNotificationThread,
                          notification, &notificationThread);
    if (err != 0) {
        Limelog("Unable to start second display failure callback thread: %d\n", err);
        free(notification);
        return;
    }

    PltDetachThread(&notificationThread);
}

