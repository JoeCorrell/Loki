static void secondStreamConnectionTerminated(int errorCode) {
    atomic_store(&secondStreamFailureCode, errorCode);
    if (atomic_exchange(&secondStreamFailed, true)) {
        return;
    }

    Limelog("Second display stream ended: %d. Continuing with one display.\n", errorCode);
    notifySecondDisplayFailure(errorCode);
}

