void LiInitializeSecondDisplay(int width, int height, int fps, int bitrateKbps,
                               PDECODER_RENDERER_CALLBACKS drCallbacks,
                               SECOND_DISPLAY_STATUS_CALLBACK statusCallback) {
    bool mutexInitialized = atomic_load(&secondStreamLifecycleMutexInitialized);

    if (mutexInitialized) {
        PltLockMutex(&secondStreamLifecycleMutex);
    }

    memset(&SecondStreamConfig, 0, sizeof(SecondStreamConfig));
    memset(&VideoCallbacks2, 0, sizeof(VideoCallbacks2));
    memset(&VideoPingPayload2, 0, sizeof(VideoPingPayload2));

    SecondStreamConfig.width = width;
    SecondStreamConfig.height = height;
    SecondStreamConfig.fps = fps;
    SecondStreamConfig.bitrate = bitrateKbps;

    if (drCallbacks != NULL) {
        VideoCallbacks2 = *drCallbacks;
    }

    atomic_store(&secondStreamStatusCallback, statusCallback);
    atomic_fetch_add(&secondStreamGeneration, 1);
    atomic_store(&secondStreamFailed, false);
    atomic_store(&secondStreamInitialized, false);
    atomic_store(&secondStreamStarted, false);
    atomic_store(&secondStreamStatusActive, false);
    atomic_store(&secondStreamFailureCode, 0);
    VideoPortNumber2 = 0;

    SecondStreamEnabled = drCallbacks != NULL && width > 0 && height > 0 &&
                          fps > 0 && bitrateKbps > 0;

    if (mutexInitialized) {
        PltUnlockMutex(&secondStreamLifecycleMutex);
    }
}

void LiPrepareSecondDisplay(void) {
    if (!SecondStreamEnabled) {
        return;
    }

    if (!atomic_load(&secondStreamLifecycleMutexInitialized)) {
        int mutexErr = PltCreateMutex(&secondStreamLifecycleMutex);
        if (mutexErr != 0) {
            Limelog("Unable to create second display lifecycle mutex: %d\n", mutexErr);
            LiDisableSecondDisplay();
            return;
        }
        atomic_store(&secondStreamLifecycleMutexInitialized, true);
    }

    PltLockMutex(&secondStreamLifecycleMutex);

    int width = SecondStreamConfig.width;
    int height = SecondStreamConfig.height;
    int fps = SecondStreamConfig.fps;
    int bitrate = SecondStreamConfig.bitrate;

    // Copy only after LiStartConnection() has installed this session's keys,
    // codec flags, packet size, colour mode, and remote/local policy.
    SecondStreamConfig = StreamConfig;
    SecondStreamConfig.width = width;
    SecondStreamConfig.height = height & ~0x1;
    SecondStreamConfig.fps = fps;
    SecondStreamConfig.bitrate = bitrate;

    if (height != SecondStreamConfig.height) {
        Limelog("Second display encoder height must not be odd. Rounding %d to %d\n",
                height, SecondStreamConfig.height);
    }

    if (SecondStreamConfig.height == 0) {
        Limelog("Second display encoder height is invalid after alignment\n");
        SecondStreamEnabled = false;
    }

    PltUnlockMutex(&secondStreamLifecycleMutex);
}

void LiSetSecondDisplayPacketSize(int packetSize) {
    bool mutexInitialized = atomic_load(&secondStreamLifecycleMutexInitialized);

    if (mutexInitialized) {
        PltLockMutex(&secondStreamLifecycleMutex);
    }

    if (SecondStreamEnabled) {
        SecondStreamConfig.packetSize = packetSize;
    }

    if (mutexInitialized) {
        PltUnlockMutex(&secondStreamLifecycleMutex);
    }
}

int LiStartSecondDisplayStream(void* rendererContext, int drFlags) {
    int err;

    if (!LiIsSecondDisplayNegotiated()) {
        return 0;
    }

    if (!atomic_load(&secondStreamLifecycleMutexInitialized)) {
        return -1;
    }

    PltLockMutex(&secondStreamLifecycleMutex);

    // A Surface detach may race with the RTSP-to-start transition.
    if (!SecondStreamEnabled || VideoPortNumber2 == 0) {
        PltUnlockMutex(&secondStreamLifecycleMutex);
        return 0;
    }

    atomic_store(&secondStreamFailed, false);
    initializeVideoStream2();
    atomic_store(&secondStreamInitialized, true);

    err = startVideoStream2(rendererContext, drFlags);
    if (err != 0) {
        destroyVideoStream2();
        atomic_store(&secondStreamInitialized, false);
        SecondStreamEnabled = false;
        VideoPortNumber2 = 0;
        PltUnlockMutex(&secondStreamLifecycleMutex);
        return err;
    }

    // A receive failure can occur immediately after its thread is created. Do
    // not announce an active display after that failure has already happened.
    if (atomic_load(&secondStreamFailed)) {
        stopVideoStream2();
        destroyVideoStream2();
        atomic_store(&secondStreamInitialized, false);
        SecondStreamEnabled = false;
        VideoPortNumber2 = 0;
        PltUnlockMutex(&secondStreamLifecycleMutex);
        return -1;
    }

    atomic_store(&secondStreamStarted, true);
    PltUnlockMutex(&secondStreamLifecycleMutex);

    // A Surface can be detached immediately after the start lock is released.
    // Do not resurrect the UI's active state after that teardown completed.
    if (atomic_load(&secondStreamStarted)) {
        notifySecondDisplayStatus(true, 0);

        /*
         * The receive thread can fail after the pre-start failure check but
         * before the active transition above. Its first notification observes
         * an already-inactive status and intentionally emits nothing. Recheck
         * after publishing so that race is closed with an ordered inactive
         * callback carrying the original failure code.
         */
        if (atomic_load(&secondStreamFailed)) {
            notifySecondDisplayFailure(atomic_load(&secondStreamFailureCode));
        }
    }
    return 0;
}

void LiStopSecondDisplayStream(void) {
    bool mutexInitialized = atomic_load(&secondStreamLifecycleMutexInitialized);

    if (mutexInitialized) {
        PltLockMutex(&secondStreamLifecycleMutex);
    }

    if (atomic_exchange(&secondStreamStarted, false)) {
        stopVideoStream2();
    }

    if (atomic_exchange(&secondStreamInitialized, false)) {
        destroyVideoStream2();
    }

    SecondStreamEnabled = false;
    VideoPortNumber2 = 0;

    if (mutexInitialized) {
        PltUnlockMutex(&secondStreamLifecycleMutex);
    }

    // This is idempotent. An asynchronous failure transitions the status first,
    // so subsequent Surface teardown cannot issue a duplicate callback.
    notifySecondDisplayStatus(false, 0);
}

void LiHandleSecondDisplayTermination(int errorCode) {
    // Report the host's reason before teardown. This transitions the status
    // atomically, so LiStopSecondDisplayStream() cannot emit a second inactive
    // notification with an unhelpful zero error code.
    secondStreamConnectionTerminated(errorCode);
    LiStopSecondDisplayStream();
}

void LiDestroySecondDisplayState(void) {
    LiStopSecondDisplayStream();

    atomic_fetch_add(&secondStreamGeneration, 1);
    atomic_store(&secondStreamStatusCallback, NULL);

    if (atomic_exchange(&secondStreamLifecycleMutexInitialized, false)) {
        PltDeleteMutex(&secondStreamLifecycleMutex);
    }
}

void LiDisableSecondDisplay(void) {
    bool mutexInitialized = atomic_load(&secondStreamLifecycleMutexInitialized);

    if (mutexInitialized) {
        PltLockMutex(&secondStreamLifecycleMutex);
    }

    SecondStreamEnabled = false;
    VideoPortNumber2 = 0;

    if (mutexInitialized) {
        PltUnlockMutex(&secondStreamLifecycleMutex);
    }
}

bool LiIsSecondDisplayNegotiated(void) {
    bool mutexInitialized = atomic_load(&secondStreamLifecycleMutexInitialized);
    bool negotiated;

    if (mutexInitialized) {
        PltLockMutex(&secondStreamLifecycleMutex);
    }

    negotiated = SecondStreamEnabled && !atomic_load(&secondStreamFailed) &&
                 VideoPortNumber2 != 0;

    if (mutexInitialized) {
        PltUnlockMutex(&secondStreamLifecycleMutex);
    }

    return negotiated;
}

bool LiIsSecondDisplayRequested(void) {
    bool mutexInitialized = atomic_load(&secondStreamLifecycleMutexInitialized);
    bool requested;

    if (mutexInitialized) {
        PltLockMutex(&secondStreamLifecycleMutex);
    }

    requested = SecondStreamEnabled;

    if (mutexInitialized) {
        PltUnlockMutex(&secondStreamLifecycleMutex);
    }

    return requested;
}

bool LiIsSecondDisplayActive(void) {
    return LiIsSecondDisplayNegotiated() && atomic_load(&secondStreamStarted);
}
